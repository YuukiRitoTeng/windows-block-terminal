export type UiTextKey = keyof typeof uiTextDictionary;

export function uiText(key: UiTextKey, values: Record<string, UiTextValue> = {}): string {
    const template = (uiTextDictionary as Record<string, string>)[key];
    if (template == null) {
        return `[${String(key)}]`;
    }
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
        return Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match;
    });
}
